"""Build public/scripture.js from the Douay-Rheims Bible (Challoner revision, 1899 American edition text).

Usage: python3 tools/import_dra.py [DRC.json]

Without an argument it downloads DRC.json from the scrollmapper/bible_databases project on GitHub
(public-domain text). It reads the passage list from public/index.html and writes only those verses.
"""
import json, pathlib, re, sys, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "public"
SOURCE = "https://raw.githubusercontent.com/scrollmapper/bible_databases/master/formats/json/DRC.json"

# Book names used in index.html -> names in DRC.json
BOOK_NAMES = {"1 Corinthians": "I Corinthians", "Revelation": "Revelation of John"}


def load_bible(path=None):
    raw = pathlib.Path(path).read_bytes() if path else urllib.request.urlopen(SOURCE).read()
    data = json.loads(raw)
    return {b["name"]: {c["chapter"]: {v["verse"]: v["text"] for v in c["verses"]} for c in b["chapters"]}
            for b in data["books"]}


def needed_spans():
    """Read the passage list straight out of index.html so the two never drift apart."""
    html = (SITE / "index.html").read_text()
    for book, args in re.findall(r'P\("([^"]+)",\s*((?:\[[^\]]*\](?:,\s*)?)+)\)', html):
        for span in re.findall(r"\[([^\]]*)\]", args):
            yield book, [int(x) for x in span.split(",") if x.strip()]


def main():
    bible = load_bible(sys.argv[1] if len(sys.argv) > 1 else None)
    data, missing = {}, []
    for book, nums in needed_spans():
        chap = bible.get(BOOK_NAMES.get(book, book), {}).get(nums[0], {})
        verses = sorted(chap) if len(nums) == 1 else range(nums[1], (nums[2] if len(nums) > 2 else nums[1]) + 1)
        for v in verses:
            if v in chap:
                # Each verse starts its own line, as the Douay-Rheims is traditionally printed.
                data.setdefault(book, {}).setdefault(str(nums[0]), {})[str(v)] = "\n" + " ".join(chap[v].split())
            else:
                missing.append(f"{book} {nums[0]}:{v}")

    js = ("// Douay-Rheims Bible (Challoner revision), public domain. SCRIPTURE[book][chapter][verse].\n"
          "// Generated by tools/import_dra.py. Do not edit by hand.\n"
          "// A verse beginning with \"\\n\" starts a new line; \"¶\" would start a new paragraph.\n"
          "window.SCRIPTURE = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    (SITE / "scripture.js").write_text(js)
    print(f"wrote {sum(len(c) for b in data.values() for c in b.values())} verses to public/scripture.js")
    if missing:
        print("missing:", ", ".join(missing))
        sys.exit(1)


if __name__ == "__main__":
    main()
